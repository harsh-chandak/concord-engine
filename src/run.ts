/**
 * Finishing a run: proving it, writing it down, and saying what it cost.
 *
 * All three are derived, never asserted. `accept` runs the commands the
 * contract named. `docs` renders the decision log. `cost` measures bytes it
 * can see and refuses to call them tokens.
 */
import { spawnSync } from "node:child_process";
import { kindSpec, normalizeSubject } from "./compare.js";
import { briefFor } from "./contract.js";
import type { CheckResult, Contract, Decision } from "./types.js";

/**
 * Runs every acceptance check. All at once rather than in dependency order:
 * a check that only passes when run after another check has a hidden
 * dependency, and hiding it in the runner is how it stays hidden.
 */
export function runAcceptance(contract: Contract, cwd = process.cwd()): CheckResult[] {
  return contract.acceptance.map((a) => {
    const started = Date.now();
    const res = spawnSync(a.check, {
      cwd, shell: true, encoding: "utf8", timeout: 10 * 60_000,
      env: { ...process.env, ORCHESTRAGUARD_ACCEPTANCE: a.id },
    });
    const output = [res.stdout, res.stderr].filter(Boolean).join("").trim();
    return {
      id: a.id, statement: a.statement, check: a.check, unit: a.unit,
      passed: res.status === 0,
      code: res.status,
      ms: Date.now() - started,
      // Keep the tail: a failing command says why at the end, not the start.
      output: output.length > 2000 ? `…\n${output.slice(-2000)}` : output,
    };
  });
}

/**
 * The design doc nobody writes. Generated from the log, so it cannot drift
 * from what was actually decided — it is the same data the gate compares
 * against, rendered.
 */
export function generateDocs(contract: Contract, decisions: Decision[]): string {
  // The subject key must be the SAME key the rest of the package uses.
  // It was `.toLowerCase()` here and `normalizeSubject()` everywhere else,
  // which meant two decisions the detector treats as one conflict —
  // "user identifier in API payloads" and "User Identifier in API Payloads!" —
  // rendered as two separate entries, both under "Decisions in force", under a
  // heading promising each was enforced. The tool's own failure mode, printed
  // in the tool's own output.
  const byId = new Map(decisions.map((d) => [d.id, d]));
  const active = new Map<string, Decision>();
  const superseded: Decision[] = [];
  for (const d of decisions) {
    // Look the replaced decision up by id across the whole log, not in the
    // active map: a later decision on the same subject may already have
    // displaced it, and it would then vanish from the record entirely.
    if (d.supersedes) {
      const prior = byId.get(d.supersedes);
      if (prior) superseded.push(prior);
    }
    active.set(`${d.kind}::${normalizeSubject(d.subject)}`, d);
  }

  const byKind = new Map<string, Decision[]>();
  for (const d of active.values()) {
    byKind.set(d.kind, [...(byKind.get(d.kind) ?? []), d]);
  }

  const out: string[] = [
    `# ${contract.id}`,
    ``,
    contract.goal,
    ``,
    `## Scope`,
    ``,
    `**In.** ${contract.scope.in.join("; ") || "—"}`,
    ``,
    `**Out.** ${contract.scope.out.join("; ") || "—"}`,
    ``,
    `## Decisions in force`,
    ``,
    `Generated from the decision log. Every entry was recorded before or during`,
    `the work, and each one was enforced on every worker that touched it.`,
    ``,
  ];

  if (!active.size) out.push(`_No decisions recorded._`, ``);
  for (const [kind, list] of [...byKind.entries()].sort()) {
    out.push(`### ${kind}`, ``);
    for (const d of list.sort((a, b) => a.subject.localeCompare(b.subject))) {
      const spec = kindSpec(d.kind);
      out.push(`- **${d.subject}** — \`${spec.render(spec.parse(d.value))}\``);
      out.push(`  ${d.rationale ? d.rationale : "_no rationale recorded_"}  `);
      out.push(`  <sub>${d.id} · ${d.author} (${d.layer}) · ${d.at}</sub>`);
    }
    out.push(``);
  }

  if (superseded.length) {
    out.push(`## Decisions that were replaced`, ``,
      `Kept because the reason a choice was reversed is the part people need later.`, ``);
    for (const d of superseded) {
      const spec = kindSpec(d.kind);
      out.push(`- ~~**${d.subject}** — \`${spec.render(spec.parse(d.value))}\`~~ <sub>(${d.id}, ${d.author})</sub>`);
    }
    out.push(``);
  }

  out.push(`## How this was proved`, ``, `| criterion | unit | command |`, `| --- | --- | --- |`);
  for (const a of contract.acceptance) out.push(`| ${a.statement} | \`${a.unit}\` | \`${a.check}\` |`);
  out.push(``, `<sub>Generated by \`orchestraguard docs\` from the decision log. Do not edit by hand.</sub>`, ``);
  return out.join("\n");
}

export interface CostLine {
  unit: string;
  briefBytes: number;
  baselineBytes: number;
}

export interface CostReport {
  contract: string;
  lines: CostLine[];
  briefTotal: number;
  baselineTotal: number;
  ratio: number;
  /** Characters per token. An assumption, stated, not a measurement. */
  charsPerToken: number;
  estimatedBriefTokens: number;
  estimatedBaselineTokens: number;
}

/**
 * What the fan-out cost, as far as the package can honestly tell.
 *
 * The baseline is what each worker would have received had it been handed the
 * whole contract instead of its brief — which is the realistic alternative,
 * not a straw man. No tokenizer ships with this package, so the token figures
 * are a stated division, labelled as an estimate everywhere they surface.
 */
export function costReport(contract: Contract, active: Decision[] = [], charsPerToken = 4): CostReport {
  const baseline = JSON.stringify(contract).length;
  const lines: CostLine[] = contract.units.map((u) => ({
    unit: u.id,
    briefBytes: briefFor(contract, u.id, active).instructions.length,
    baselineBytes: baseline,
  }));
  const briefTotal = lines.reduce((n, l) => n + l.briefBytes, 0);
  const baselineTotal = lines.reduce((n, l) => n + l.baselineBytes, 0);
  return {
    contract: contract.id,
    lines,
    briefTotal,
    baselineTotal,
    ratio: baselineTotal === 0 ? 1 : briefTotal / baselineTotal,
    charsPerToken,
    estimatedBriefTokens: Math.round(briefTotal / charsPerToken),
    estimatedBaselineTokens: Math.round(baselineTotal / charsPerToken),
  };
}
